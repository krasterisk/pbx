import ExcelJS from 'exceljs';
import { createHash } from 'node:crypto';
import type { ReportColumn } from '../callcenter/reports/callcenter-reports.types';

/** Branded provenance, not a cryptographic signature or an assertion of legal certification. */
export async function buildAutodialXlsx(name: string, columns: ReportColumn[], rows: Array<Record<string, unknown>>,
  metadata: { tenant: number; from: string; to: string; timezone: string }): Promise<Buffer> {
  const workbook = new ExcelJS.Workbook(); workbook.creator = 'Krasterisk'; workbook.title = name;
  workbook.subject = `Autodial · tenant ${metadata.tenant}`; workbook.created = new Date();
  const sheet = workbook.addWorksheet(name.slice(0, 31));
  const dateKeys = new Set(columns.filter((column) => column.type === 'datetime' || /_at$/.test(column.key)).map((column) => column.key));
  sheet.columns = columns.map((column) => ({ header: dateKeys.has(column.key) ? `${column.header} (${metadata.timezone})` : column.header,
    key: column.key, width: dateKeys.has(column.key) ? 24 : Math.min(60, Math.max(14, column.header.length + 3)) }));
  const formatter = new Intl.DateTimeFormat('en-CA', { timeZone: metadata.timezone, year: 'numeric', month: '2-digit', day: '2-digit',
    hour: '2-digit', minute: '2-digit', second: '2-digit', hourCycle: 'h23' });
  for (const row of rows) {
    const added = sheet.addRow(columns.map((column) => {
      const value = row[column.key];
      if (dateKeys.has(column.key) && value) {
        const date = new Date(String(value)); if (!Number.isFinite(date.getTime())) return String(value);
        const p = Object.fromEntries(formatter.formatToParts(date).map((part) => [part.type, part.value]));
        return new Date(Date.UTC(Number(p.year), Number(p.month) - 1, Number(p.day), Number(p.hour), Number(p.minute), Number(p.second)));
      }
      return value && typeof value === 'object' ? JSON.stringify(value) : value ?? null;
    }));
    columns.forEach((column, index) => { const cell = added.getCell(index + 1);
      if (cell.value instanceof Date) cell.numFmt = 'dd.mm.yyyy hh:mm:ss';
      else if (typeof cell.value === 'number') cell.numFmt = /rate|rpc|asr|penetration/.test(column.key) ? '0.00"%"' : Number.isInteger(cell.value) ? '0' : '#,##0.00';
      else cell.numFmt = '@';
    });
  }
  sheet.getRow(1).font = { bold: true }; sheet.views = [{ state: 'frozen', ySplit: 1 }];
  if (columns.length) sheet.autoFilter = { from: { row: 1, column: 1 }, to: { row: 1, column: columns.length } };
  const info = workbook.addWorksheet('Provenance');
  info.columns = [{ width: 24 }, { width: 100 }];
  info.addRows([['Generated by', 'Krasterisk Autodial'], ['Tenant', metadata.tenant], ['Period', `${metadata.from} — ${metadata.to}`],
    ['Reporting timezone', metadata.timezone], ['Generated UTC', workbook.created.toISOString()], ['Rows', rows.length],
    ['Data SHA-256', createHash('sha256').update(JSON.stringify(rows)).digest('hex')]]);
  return Buffer.from(await workbook.xlsx.writeBuffer());
}
