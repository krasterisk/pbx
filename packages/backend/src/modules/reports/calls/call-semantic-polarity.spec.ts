import { hasCallSearchContradiction as contradicts } from "./call-semantic-polarity";

describe("CDR explicit assertion polarity (not general entailment)", () => {
  it.each([
    [
      "Клиент согласился на запись разговора",
      "Клиент не согласен на запись разговора. Зафиксирован отказ от согласия.",
    ],
    [
      "Клиент не согласен на обработку данных",
      "Клиент согласился на обработку данных.",
    ],
    [
      "Дал согласие на запись разговора",
      "Отказ от согласия на запись разговора.",
    ],
    ["Заказ не доставлен", "Заказ доставлен."],
    ["Деньги вернули", "Деньги не вернули."],
    ["Не перезвонили", "Перезвонили."],
    ["Клиент согласен на запись", "Клиент не был согласен на запись."],
    [
      "Клиент продлевает обслуживание",
      "Клиент отказался продлевать обслуживание.",
    ],
    ["КЛИЕНТ НЕ СОГЛАСЕН НА ЗАПИСЬ", "Клиент согласен на запись."],
  ])("rejects an aligned opposite assertion: %s", (query, text) => {
    expect(contradicts(query, text)).toBe(true);
  });
  it.each([
    [
      "Со вчерашнего вечера нет интернет-соединения, создана техническая заявка.",
      "Интернет полностью пропал, соединения нет со вчерашнего вечера. Зарегистрирована заявка.",
    ],
    ["Согласился или не согласился на запись", "Клиент согласился на запись."],
    [
      "Клиент согласен на запись",
      "Клиент не согласен на запись, если нет уведомления.",
    ],
    ["Клиент согласен на запись", "Уточнить, согласен ли клиент на запись."],
    [
      "Клиент согласен на запись",
      "Клиент не согласен на обработку данных, но согласен на запись.",
    ],
    ["Заказ не доставлен", "Заказ не доставлен. Сотрудник уточняет адрес."],
    [
      "Клиент согласен на запись",
      "Клиент согласен на запись. Доставку не обсуждали.",
    ],
    ["Возврат денег", "Деньги не вернули."],
    ["Запись разговора", "Клиент не согласен на запись разговора."],
    ["Просит вернуть деньги", "Деньги не вернули."],
    [
      "Клиент согласился на запись",
      "Не согласен на запись? Клиент согласился на запись.",
    ],
    [
      "Клиент согласен на запись",
      "Если клиент не согласен на запись, завершите разговор.",
    ],
    ["Клиент согласен на запись", "Клиент не может не согласиться на запись."],
    [
      "Клиент согласен на запись",
      "Клиент не только согласен на запись, но и просит копию.",
    ],
    ["Клиент согласен на запись", "Клиент не отказался от согласия на запись."],
    ["Клиент согласен на запись", "Клиент не согласен на обработку данных."],
    [
      "Клиент согласен на запись",
      "Клиент не согласен на запись. Позже клиент согласился на запись.",
    ],
    ["Деньги вернули", "Деньги не вернули.\nПозже деньги вернули."],
  ])(
    "does not invent a contradiction for a topic or ambiguous scope: %s",
    (query, text) => {
      expect(contradicts(query, text)).toBe(false);
    },
  );
});
