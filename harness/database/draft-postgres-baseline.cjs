'use strict';
// Offline draft helper. Review the emitted SQL and test it on a disposable PG;
// production migrations load only the committed static .sql artifact.
const { inventory } = require('./schema-inventory.cjs');

const quote = name => `"${name.replaceAll('"', '""')}"`;
const columnList = text => text.replaceAll(/`([^`]+)`/g, (_, name) => quote(name));

function columnSql(table, column, definition, enums) {
  let type;
  let suffix;
  if (definition.startsWith('ENUM(')) {
    let depth = 0;
    let end = -1;
    for (let i = 0; i < definition.length; i++) {
      if (definition[i] === '(') depth++;
      if (definition[i] === ')' && --depth === 0) { end = i; break; }
      if (definition[i] !== ')') depth += 0;
    }
    if (end < 0) throw new Error(`Invalid ENUM ${table}.${column}`);
    const values = definition.slice(5, end);
    const enumName = `enum_${table}_${column}`;
    if (Buffer.byteLength(enumName) > 63) throw new Error(`Enum name too long: ${enumName}`);
    enums.push(`CREATE TYPE ${quote(enumName)} AS ENUM (${values});`);
    type = quote(enumName);
    suffix = definition.slice(end + 1);
  } else {
    const match = /^([A-Z]+(?:\([^)]*\))?)( UNSIGNED)?(.*)$/.exec(definition);
    if (!match) throw new Error(`Unsupported column ${table}.${column}: ${definition}`);
    const [, mysqlType, unsigned, tail] = match;
    suffix = tail;
    if (/^VARCHAR\(\d+\)$/.test(mysqlType) || /^CHAR\(\d+\)$/.test(mysqlType) || /^DECIMAL\(\d+,\d+\)$/.test(mysqlType)) type = mysqlType;
    else type = ({ INTEGER: 'INTEGER', BIGINT: 'BIGINT', TINYINT: 'SMALLINT', 'TINYINT(1)': 'BOOLEAN',
      TEXT: 'TEXT', MEDIUMTEXT: 'TEXT', DATETIME: 'TIMESTAMP WITH TIME ZONE', DATE: 'DATE', JSON: 'JSON', FLOAT: 'REAL' })[mysqlType];
    if (!type) throw new Error(`Unsupported type ${table}.${column}: ${mysqlType}`);
    if (unsigned) {
      if (mysqlType === 'INTEGER') type = 'BIGINT';
      else if (mysqlType === 'TINYINT') type = 'SMALLINT';
      else throw new Error(`Unsupported unsigned type ${table}.${column}: ${mysqlType}`);
      const max = mysqlType === 'INTEGER' ? 4294967295 : 255;
      suffix += ` CHECK (${quote(column)} BETWEEN 0 AND ${max})`;
    }
  }
  suffix = suffix.replace(/\bauto_increment\b/i, 'GENERATED BY DEFAULT AS IDENTITY');
  if (type === 'BOOLEAN') suffix = suffix.replace(/\bDEFAULT (?:0|1)\b/gi, value => value.endsWith('0') ? 'DEFAULT false' : 'DEFAULT true');
  const allowed = suffix.replace(/\bGENERATED BY DEFAULT AS IDENTITY\b|\bNOT NULL\b|\bDEFAULT (?:NULL|true|false|-?\d+(?:\.\d+)?|'(?:[^']|'')*')|\bUNIQUE\b|\bCHECK \([^)]*\)/gi, '').trim();
  if (allowed) throw new Error(`Unsupported column options ${table}.${column}: ${suffix}`);
  return `${quote(column)} ${type}${suffix}`;
}

function draft() {
  const { baselineTables, differences, sources } = inventory();
  if (sources.baselineSha256 !== '8c18e47d94da3c3aeca3807eb44dbd0280433c1dedf96bef36470203d699543d'
    || sources.modelMetadataSha256 !== '1aa7a2ac56ad8b01414fafc19b25dfa96ff138d4da000724070da775a705a797'
    || Object.entries(differences).some(([kind, rows]) => kind !== 'intentionalTypeWidenings' && rows.length)) {
    throw new Error('Source schema changed; review before drafting PostgreSQL baseline');
  }
  const enums = [];
  const tables = [];
  const foreignKeys = [];
  const indexes = [];
  for (const [table, metadata] of Object.entries(baselineTables)) {
    const parts = Object.entries(metadata.columns).map(([column, definition]) => columnSql(table, column, definition, enums));
    for (const constraint of metadata.constraints) {
      if (constraint.startsWith('PRIMARY KEY ')) parts.push(columnList(constraint));
      else if (constraint.startsWith('FOREIGN KEY ')) {
        foreignKeys.push(`ALTER TABLE ${quote(table)} ADD ${columnList(constraint)};`);
        const columns = /^FOREIGN KEY \((`[^`]+`(?:, `[^`]+`)*)\)/.exec(constraint)?.[1];
        if (!columns) throw new Error(`Unsupported foreign key ${table}: ${constraint}`);
        const firstColumn = columns.split(', ')[0];
        const indexed = metadata.constraints.some(other =>
          /^(?:UNIQUE )?INDEX `[^`]+` \(/.test(other) && other.slice(other.indexOf('(') + 1).startsWith(firstColumn));
        if (indexed) continue;
        const indexName = `idx_${table}_${columns.replaceAll('`', '').replaceAll(', ', '_')}_fk`;
        if (Buffer.byteLength(indexName) > 63) throw new Error(`Foreign key index name too long: ${indexName}`);
        indexes.push(`CREATE INDEX ${quote(indexName)} ON ${quote(table)} (${columnList(columns)});`);
      } else {
        const index = /^(UNIQUE )?INDEX `([^`]+)` \((.*)\)$/.exec(constraint);
        if (!index) throw new Error(`Unsupported constraint ${table}: ${constraint}`);
        indexes.push(`CREATE ${index[1] || ''}INDEX ${quote(index[2])} ON ${quote(table)} (${columnList(index[3])});`);
      }
    }
    tables.push(`CREATE TABLE ${quote(table)} (\n  ${parts.join(',\n  ')}\n);`);
  }
  return [
    '-- DB-02 PostgreSQL baseline: reviewed schema snapshot of the 112 AppModule models.',
    '-- Empty UTF8 database only. Timestamps are UTC instants (TIMESTAMPTZ).',
    '-- Asterisk queue_log/CEL writer and legacy data adoption belong to DB-03.',
    '-- Source MySQL 0001 SHA-256: ' + sources.baselineSha256,
    "DO $$ BEGIN IF current_setting('server_encoding') <> 'UTF8' THEN RAISE EXCEPTION 'Krasterisk requires UTF8 database encoding'; END IF; END $$;",
    '', ...enums, '', ...tables, '', ...indexes, '', ...foreignKeys, '',
  ].join('\n');
}

if (require.main === module) {
  try { process.stdout.write(draft()); }
  catch (error) { process.stderr.write(`PG baseline draft failed: ${error.message}\n`); process.exitCode = 1; }
}
module.exports = { draft };
